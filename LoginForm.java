    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int row = tblReservationList.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this, "Click a reservation in the list first.");
        return;
    }
    String id = tblReservationList.getValueAt(row, 0).toString();
    int confirm = JOptionPane.showConfirmDialog(this,
        "Delete reservation " + id + "?",
        "Confirm Delete", JOptionPane.YES_NO_OPTION);
    if (confirm == JOptionPane.YES_OPTION) {
        try{
        roomController.deleteReservation(id);
        loadReservations();
        JOptionPane.showMessageDialog(this, "Reservation deleted.");
    }catch(Exception e){
        JOptionPane.showMessageDialog(this,"Delete failed:"+ e.getMessage());
    }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

