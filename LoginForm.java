    private void btnSearchReserveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchReserveActionPerformed
String keyword = txtSearchReserve.getText().trim();

    if (keyword.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter something to search.");
        return;
    }

    try {
        List<RoomModel> results =
                roomController.searchReservations(keyword);
DefaultTableModel model=(DefaultTableModel)
        tblReservationList.getModel();
model.setRowCount(0);

        for (RoomModel r : results) {
            model.addRow(new Object[]{
                r.getReservationId(),
                r.getGuestName(),
                r.getRoomNo(),
                r.getCheckIn(),
                r.getCheckOut(),
                r.getTotalAmount(),
                r.getStatus()
            });
        }

        if (results.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "No matching reservation found.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Search Error: " + e.getMessage());
    }  // TODO add your handling code here:
    }//GEN-LAST:event_btnSearchReserveActionPerformed

