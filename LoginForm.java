    private void loadReservations() {
        try {
            javax.swing.table.DefaultTableModel tableModel =
                (javax.swing.table.DefaultTableModel) tblReservationList.getModel();
            tableModel.setRowCount(0);

            for (RoomModel r : roomController.getAllReservations()) {
                tableModel.addRow(new Object[]{
                    r.getReservationId(),
                    r.getGuestName(),
                    r.getRoomNo(),
                    r.getCheckIn(),
                    r.getCheckOut(),
                    r.getTotalAmount(),
                    r.getStatus()
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Could not load reservations: " + e.getMessage());
        }
    }
    
    private void btnsigninActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsigninActionPerformed
    String email = txtEmail.getText().trim();
    String password = new String(txtPassword.getPassword()).trim();

    if (email.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter email and password");
        return;
    }

    LogInModel model = new LogInModel();
    model.setEmail(email);
    model.setPassword(password);

    LogInController controller = new LogInController();
    LogInModel loggedUser = controller.loginAndGetUser(model);

    if (loggedUser != null) {
        JOptionPane.showMessageDialog(this, "Welcome, " + loggedUser.getFullName());
        JOptionPane.showMessageDialog(this, "LOGIN SUCCESS! Now we just need to find your dashboard");
    jTabbedPane1.setSelectedIndex(3);
      
    } else {
        JOptionPane.showMessageDialog(this, "Invalid email or password");
 
    }//GEN-LAST:event_btnsigninActionPerformed
    }
